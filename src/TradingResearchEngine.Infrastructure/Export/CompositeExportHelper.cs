    /// <summary>
    /// Generates MQL4 Expert Advisor code from a composite strategy configuration.
    /// </summary>
    public static (string Code, List<string> Warnings) GenerateMQL4(CompositeStrategyConfig config)
    {
        var warnings = new List<string>();
        var sb = new StringBuilder();

        sb.AppendLine("//+------------------------------------------------------------------+");
        sb.AppendLine($"//| {config.Name} EA (Composite)                                      |");
        sb.AppendLine("//| Generated by TradingResearchEngine                                |");
        sb.AppendLine("//+------------------------------------------------------------------+");
        sb.AppendLine("#property strict");
        sb.AppendLine();
        sb.AppendLine("// NOTE: Composite strategy export — signal timing may differ from backtest");
        sb.AppendLine("input double LotSize = 0.1;");
        sb.AppendLine();

        // Declare indicator variables
        foreach (var ind in config.Indicators)
        {
            var varDecls = GetMQL4IndicatorDeclarations(ind, warnings);
            foreach (var decl in varDecls)
                sb.AppendLine(decl);
        }

        sb.AppendLine();
        sb.AppendLine("int OnInit()");
        sb.AppendLine("{");
        sb.AppendLine("    return INIT_SUCCEEDED;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void OnDeinit(const int reason)");
        sb.AppendLine("{");
        sb.AppendLine("    // Cleanup");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void OnTick()");
        sb.AppendLine("{");

        // Compute indicator values
        foreach (var ind in config.Indicators)
        {
            var computeLines = GetMQL4IndicatorComputation(ind, warnings);
            foreach (var line in computeLines)
                sb.AppendLine($"    {line}");
        }

        sb.AppendLine();

        // Parse and translate entry condition
        var entryExpr = TranslateConditionMQL(config.EntryCondition, config.Indicators, warnings);
        var exitExpr = TranslateConditionMQL(config.ExitCondition, config.Indicators, warnings);

        sb.AppendLine($"    // Entry condition");
        sb.AppendLine($"    bool entrySignal = {entryExpr};");
        sb.AppendLine($"    // Exit condition");
        sb.AppendLine($"    bool exitSignal = {exitExpr};");
        sb.AppendLine();
        sb.AppendLine("    if (entrySignal && OrdersTotal() == 0)");
        sb.AppendLine("    {");
        sb.AppendLine($"        OrderSend(Symbol(), OP_BUY, LotSize, Ask, 3, 0, 0, \"{config.Name}\", 0, 0, clrGreen);");
        sb.AppendLine("    }");
        sb.AppendLine("    else if (exitSignal && OrdersTotal() > 0)");
        sb.AppendLine("    {");
        sb.AppendLine("        for (int i = OrdersTotal() - 1; i >= 0; i--)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (OrderSelect(i, SELECT_BY_POS) && OrderSymbol() == Symbol())");
        sb.AppendLine("                OrderClose(OrderTicket(), OrderLots(), Bid, 3, clrRed);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return (sb.ToString(), warnings);
    }

    /// <summary>
    /// Generates MQL5 Expert Advisor code from a composite strategy configuration.
    /// </summary>
    public static (string Code, List<string> Warnings) GenerateMQL5(CompositeStrategyConfig config)
    {
        var warnings = new List<string>();
        var sb = new StringBuilder();

        sb.AppendLine("//+------------------------------------------------------------------+");
        sb.AppendLine($"//| {config.Name} EA (Composite, MQL5)                                |");
        sb.AppendLine("//| Generated by TradingResearchEngine                                |");
        sb.AppendLine("//+------------------------------------------------------------------+");
        sb.AppendLine("#property strict");
        sb.AppendLine("#include <Trade\\Trade.mqh>");
        sb.AppendLine();
        sb.AppendLine("// NOTE: Composite strategy export — signal timing may differ from backtest");
        sb.AppendLine("input double LotSize = 0.1;");
        sb.AppendLine();
        sb.AppendLine("CTrade trade;");

        // Declare indicator handles
        foreach (var ind in config.Indicators)
        {
            var handleDecls = GetMQL5HandleDeclarations(ind, warnings);
            foreach (var decl in handleDecls)
                sb.AppendLine(decl);
        }

        sb.AppendLine();
        sb.AppendLine("int OnInit()");
        sb.AppendLine("{");

        // Initialize indicator handles
        foreach (var ind in config.Indicators)
        {
            var initLines = GetMQL5HandleInit(ind, warnings);
            foreach (var line in initLines)
                sb.AppendLine($"    {line}");
        }

        sb.AppendLine("    return INIT_SUCCEEDED;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void OnDeinit(const int reason)");
        sb.AppendLine("{");

        // Release indicator handles
        foreach (var ind in config.Indicators)
        {
            var releaseLines = GetMQL5HandleRelease(ind);
            foreach (var line in releaseLines)
                sb.AppendLine($"    {line}");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void OnTick()");
        sb.AppendLine("{");

        // Copy indicator buffers
        foreach (var ind in config.Indicators)
        {
            var copyLines = GetMQL5BufferCopy(ind, warnings);
            foreach (var line in copyLines)
                sb.AppendLine($"    {line}");
        }

        sb.AppendLine();

        // Parse and translate entry/exit conditions
        var entryExpr = TranslateConditionMQL(config.EntryCondition, config.Indicators, warnings);
        var exitExpr = TranslateConditionMQL(config.ExitCondition, config.Indicators, warnings);

        sb.AppendLine($"    // Entry condition");
        sb.AppendLine($"    bool entrySignal = {entryExpr};");
        sb.AppendLine($"    // Exit condition");
        sb.AppendLine($"    bool exitSignal = {exitExpr};");
        sb.AppendLine();
        sb.AppendLine("    if (entrySignal && PositionsTotal() == 0)");
        sb.AppendLine("    {");
        sb.AppendLine($"        trade.Buy(LotSize, Symbol(), 0, 0, 0, \"{config.Name}\");");
        sb.AppendLine("    }");
        sb.AppendLine("    else if (exitSignal && PositionsTotal() > 0)");
        sb.AppendLine("    {");
        sb.AppendLine("        for (int i = PositionsTotal() - 1; i >= 0; i--)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (PositionGetSymbol(i) == Symbol())");
        sb.AppendLine("                trade.PositionClose(PositionGetTicket(i));");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("void OnTrade()");
        sb.AppendLine("{");
        sb.AppendLine("    // Trade event handler for position management");
        sb.AppendLine("}");

        return (sb.ToString(), warnings);
    }

    /// <summary>
    /// Generates Pine Script v6 code from a composite strategy configuration.
    /// </summary>
    public static (string Code, List<string> Warnings) GeneratePineScript(CompositeStrategyConfig config)
    {
        var warnings = new List<string>();
        var sb = new StringBuilder();

        sb.AppendLine("//@version=6");
        sb.AppendLine($"// {config.Name} (Composite Strategy)");
        sb.AppendLine("// Generated by TradingResearchEngine");
        sb.AppendLine("// NOTE: Composite strategy export — signal timing aligns with bar close");
        sb.AppendLine($"strategy(\"{config.Name}\", overlay=true, default_qty_type=strategy.percent_of_equity, default_qty_value=100)");
        sb.AppendLine();

        // Declare indicator variables
        foreach (var ind in config.Indicators)
        {
            var pineLines = GetPineScriptIndicatorDeclaration(ind, warnings);
            foreach (var line in pineLines)
                sb.AppendLine(line);
        }

        sb.AppendLine();

        // Parse and translate entry/exit conditions
        var entryExpr = TranslateConditionPineScript(config.EntryCondition, config.Indicators, warnings);
        var exitExpr = TranslateConditionPineScript(config.ExitCondition, config.Indicators, warnings);

        sb.AppendLine($"// Entry condition");
        sb.AppendLine($"longCondition = {entryExpr}");
        sb.AppendLine($"// Exit condition");
        sb.AppendLine($"exitCondition = {exitExpr}");
        sb.AppendLine();
        sb.AppendLine("if longCondition");
        sb.AppendLine("    strategy.entry(\"Long\", strategy.long)");
        sb.AppendLine();
        sb.AppendLine("if exitCondition");
        sb.AppendLine("    strategy.close(\"Long\")");

        return (sb.ToString(), warnings);
    }

    #region MQL4 Indicator Helpers

    private static List<string> GetMQL4IndicatorDeclarations(IndicatorConfig ind, List<string> warnings)
    {
        var lines = new List<string>();
        var type = ind.Type.ToLowerInvariant();

        switch (type)
        {
            case "sma":
            case "ema":
            case "rsi":
            case "atr":
                // Single-value indicators: current and previous
                break;
            case "macd":
                // Multi-value: main, signal, histogram
                break;
            case "bollinger":
                // Multi-value: upper, middle, lower
                break;
            case "stochastic":
                // Multi-value: K, D
                break;
            case "donchian":
                // Multi-value: upper, lower
                break;
            default:
                warnings.Add($"Unsupported indicator type '{ind.Type}' for MQL4 export.");
                break;
        }

        return lines;
    }

    private static List<string> GetMQL4IndicatorComputation(IndicatorConfig ind, List<string> warnings)
    {
        var lines = new List<string>();
        var type = ind.Type.ToLowerInvariant();
        var period = GetIntParam(ind.Parameters, "period", 14);

        switch (type)
        {
            case "sma":
                lines.Add($"double {ind.Id}_0 = iMA(Symbol(), 0, {period}, 0, MODE_SMA, PRICE_CLOSE, 0);");
                lines.Add($"double {ind.Id}_1 = iMA(Symbol(), 0, {period}, 0, MODE_SMA, PRICE_CLOSE, 1);");
                break;
            case "ema":
                lines.Add($"double {ind.Id}_0 = iMA(Symbol(), 0, {period}, 0, MODE_EMA, PRICE_CLOSE, 0);");
                lines.Add($"double {ind.Id}_1 = iMA(Symbol(), 0, {period}, 0, MODE_EMA, PRICE_CLOSE, 1);");
                break;
            case "rsi":
                lines.Add($"double {ind.Id}_0 = iRSI(Symbol(), 0, {period}, PRICE_CLOSE, 0);");
                lines.Add($"double {ind.Id}_1 = iRSI(Symbol(), 0, {period}, PRICE_CLOSE, 1);");
                break;
            case "atr":
                lines.Add($"double {ind.Id}_0 = iATR(Symbol(), 0, {period}, 0);");
                lines.Add($"double {ind.Id}_1 = iATR(Symbol(), 0, {period}, 1);");
                break;
            case "macd":
            {
                var fast = GetIntParam(ind.Parameters, "fastPeriod", 12);
                var slow = GetIntParam(ind.Parameters, "slowPeriod", 26);
                var signal = GetIntParam(ind.Parameters, "signalPeriod", 9);
                lines.Add($"double {ind.Id}_Macd_0 = iMACD(Symbol(), 0, {fast}, {slow}, {signal}, PRICE_CLOSE, MODE_MAIN, 0);");
                lines.Add($"double {ind.Id}_Macd_1 = iMACD(Symbol(), 0, {fast}, {slow}, {signal}, PRICE_CLOSE, MODE_MAIN, 1);");
                lines.Add($"double {ind.Id}_Signal_0 = iMACD(Symbol(), 0, {fast}, {slow}, {signal}, PRICE_CLOSE, MODE_SIGNAL, 0);");
                lines.Add($"double {ind.Id}_Signal_1 = iMACD(Symbol(), 0, {fast}, {slow}, {signal}, PRICE_CLOSE, MODE_SIGNAL, 1);");
                lines.Add($"double {ind.Id}_Histogram_0 = {ind.Id}_Macd_0 - {ind.Id}_Signal_0;");
                lines.Add($"double {ind.Id}_Histogram_1 = {ind.Id}_Macd_1 - {ind.Id}_Signal_1;");
                break;
            }
            case "bollinger":
            {
                var stdDev = GetDecimalParam(ind.Parameters, "standardDeviations", 2.0m);
                lines.Add($"double {ind.Id}_Upper_0 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_UPPER, 0);");
                lines.Add($"double {ind.Id}_Upper_1 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_UPPER, 1);");
                lines.Add($"double {ind.Id}_Middle_0 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_MAIN, 0);");
                lines.Add($"double {ind.Id}_Middle_1 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_MAIN, 1);");
                lines.Add($"double {ind.Id}_Lower_0 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_LOWER, 0);");
                lines.Add($"double {ind.Id}_Lower_1 = iBands(Symbol(), 0, {period}, {Fmt(stdDev)}, 0, PRICE_CLOSE, MODE_LOWER, 1);");
                break;
            }
            case "stochastic":
            {
                var kPeriod = GetIntParam(ind.Parameters, "kPeriod", 14);
                var dPeriod = GetIntParam(ind.Parameters, "dPeriod", 3);
                var slowing = GetIntParam(ind.Parameters, "slowing", 3);
                lines.Add($"double {ind.Id}_K_0 = iStochastic(Symbol(), 0, {kPeriod}, {dPeriod}, {slowing}, MODE_SMA, 0, MODE_MAIN, 0);");
                lines.Add($"double {ind.Id}_K_1 = iStochastic(Symbol(), 0, {kPeriod}, {dPeriod}, {slowing}, MODE_SMA, 0, MODE_MAIN, 1);");
                lines.Add($"double {ind.Id}_D_0 = iStochastic(Symbol(), 0, {kPeriod}, {dPeriod}, {slowing}, MODE_SMA, 0, MODE_SIGNAL, 0);");
                lines.Add($"double {ind.Id}_D_1 = iStochastic(Symbol(), 0, {kPeriod}, {dPeriod}, {slowing}, MODE_SMA, 0, MODE_SIGNAL, 1);");
                break;
            }
            case "donchian":
            {
                lines.Add($"double {ind.Id}_Upper_0 = High[iHighest(Symbol(), 0, MODE_HIGH, {period}, 1)];");
                lines.Add($"double {ind.Id}_Upper_1 = High[iHighest(Symbol(), 0, MODE_HIGH, {period}, 2)];");
                lines.Add($"double {ind.Id}_Lower_0 = Low[iLowest(Symbol(), 0, MODE_LOW, {period}, 1)];");
                lines.Add($"double {ind.Id}_Lower_1 = Low[iLowest(Symbol(), 0, MODE_LOW, {period}, 2)];");
                break;
            }
            default:
                lines.Add($"// NOTE: Unsupported indicator type '{ind.Type}'");
                break;
        }

        return lines;
    }

