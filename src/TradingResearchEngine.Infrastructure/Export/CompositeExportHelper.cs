    #region Condition Translation

    private static string TranslateConditionMQL(
        string conditionExpression,
        IReadOnlyList<IndicatorConfig> indicators,
        List<string> warnings)
    {
        try
        {
            var ast = ConditionParser.Parse(conditionExpression);
            return TranslateNodeMQL(ast, indicators, warnings);
        }
        catch (Exception ex)
        {
            warnings.Add($"Failed to parse condition '{conditionExpression}': {ex.Message}");
            return "false /* parse error */";
        }
    }

    private static string TranslateNodeMQL(ConditionNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        return node switch
        {
            LogicalNode logical => TranslateLogicalMQL(logical, indicators, warnings),
            ComparisonNode comparison => TranslateComparisonMQL(comparison, indicators, warnings),
            CrossNode cross => TranslateCrossMQL(cross, indicators, warnings),
            _ => "false /* unsupported node */"
        };
    }

    private static string TranslateLogicalMQL(LogicalNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var left = TranslateNodeMQL(node.Left, indicators, warnings);
        var right = TranslateNodeMQL(node.Right, indicators, warnings);
        var op = node.Operator == LogicalOperator.And ? "&&" : "||";
        return $"({left} {op} {right})";
    }

    private static string TranslateComparisonMQL(ComparisonNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var left = TranslateValueMQL(node.Left, indicators, warnings, current: true);
        var right = TranslateValueMQL(node.Right, indicators, warnings, current: true);
        var op = node.Operator switch
        {
            ComparisonOperator.GreaterThan => ">",
            ComparisonOperator.LessThan => "<",
            ComparisonOperator.GreaterThanOrEqual => ">=",
            ComparisonOperator.LessThanOrEqual => "<=",
            ComparisonOperator.Equal => "==",
            ComparisonOperator.NotEqual => "!=",
            _ => "=="
        };
        return $"{left} {op} {right}";
    }

    private static string TranslateCrossMQL(CrossNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var leftCurrent = TranslateValueMQL(node.Left, indicators, warnings, current: true);
        var rightCurrent = TranslateValueMQL(node.Right, indicators, warnings, current: true);
        var leftPrev = TranslateValueMQL(node.Left, indicators, warnings, current: false);
        var rightPrev = TranslateValueMQL(node.Right, indicators, warnings, current: false);

        if (node.Direction == CrossDirection.Above)
        {
            return $"({leftCurrent} > {rightCurrent} && {leftPrev} <= {rightPrev})";
        }
        else
        {
            return $"({leftCurrent} < {rightCurrent} && {leftPrev} >= {rightPrev})";
        }
    }

    private static string TranslateValueMQL(ValueNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings, bool current)
    {
        var shift = current ? "0" : "1";

        switch (node)
        {
            case LiteralNode literal:
                return literal.Value.ToString(CultureInfo.InvariantCulture);

            case PriceRefNode price:
                return price.Field switch
                {
                    PriceField.Open => $"Open[{shift}]",
                    PriceField.High => $"High[{shift}]",
                    PriceField.Low => $"Low[{shift}]",
                    PriceField.Close => $"Close[{shift}]",
                    PriceField.Volume => $"Volume[{shift}]",
                    _ => $"Close[{shift}]"
                };

            case IndicatorRefNode indRef:
                return GetMQLIndicatorVariable(indRef, indicators, current, warnings);

            default:
                return "0";
        }
    }

    private static string GetMQLIndicatorVariable(IndicatorRefNode indRef, IReadOnlyList<IndicatorConfig> indicators, bool current, List<string> warnings)
    {
        var suffix = current ? "_0" : "_1";
        var ind = indicators.FirstOrDefault(i => string.Equals(i.Id, indRef.IndicatorId, StringComparison.OrdinalIgnoreCase));

        if (ind is null)
        {
            warnings.Add($"Unknown indicator reference '{indRef.IndicatorId}' in condition.");
            return $"0 /* unknown: {indRef.IndicatorId} */";
        }

        var type = ind.Type.ToLowerInvariant();

        // Handle sub-properties for multi-value indicators
        if (indRef.SubProperty is not null)
        {
            var sub = indRef.SubProperty;

            // For MQL5 buffer-based access, use _buf[0] or _buf[1]
            // For MQL4, we use the pre-computed variables
            return type switch
            {
                "macd" => $"{ind.Id}_{sub}{suffix}",
                "bollinger" => $"{ind.Id}_{sub}{suffix}",
                "stochastic" => $"{ind.Id}_{sub}{suffix}",
                "donchian" => $"{ind.Id}_{sub}{suffix}",
                _ => $"{ind.Id}{suffix}"
            };
        }

        // Single-value indicators
        return type switch
        {
            "sma" or "ema" or "rsi" or "atr" => $"{ind.Id}{suffix}",
            "macd" => $"{ind.Id}_Macd{suffix}",
            "bollinger" => $"{ind.Id}_Middle{suffix}",
            "stochastic" => $"{ind.Id}_K{suffix}",
            "donchian" => $"{ind.Id}_Upper{suffix}",
            _ => $"{ind.Id}{suffix}"
        };
    }

    private static string TranslateConditionPineScript(
        string conditionExpression,
        IReadOnlyList<IndicatorConfig> indicators,
        List<string> warnings)
    {
        try
        {
            var ast = ConditionParser.Parse(conditionExpression);
            return TranslateNodePineScript(ast, indicators, warnings);
        }
        catch (Exception ex)
        {
            warnings.Add($"Failed to parse condition '{conditionExpression}': {ex.Message}");
            return "false // parse error";
        }
    }

    private static string TranslateNodePineScript(ConditionNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        return node switch
        {
            LogicalNode logical => TranslateLogicalPineScript(logical, indicators, warnings),
            ComparisonNode comparison => TranslateComparisonPineScript(comparison, indicators, warnings),
            CrossNode cross => TranslateCrossPineScript(cross, indicators, warnings),
            _ => "false // unsupported node"
        };
    }

    private static string TranslateLogicalPineScript(LogicalNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var left = TranslateNodePineScript(node.Left, indicators, warnings);
        var right = TranslateNodePineScript(node.Right, indicators, warnings);
        var op = node.Operator == LogicalOperator.And ? "and" : "or";
        return $"({left} {op} {right})";
    }

    private static string TranslateComparisonPineScript(ComparisonNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var left = TranslateValuePineScript(node.Left, indicators, warnings);
        var right = TranslateValuePineScript(node.Right, indicators, warnings);
        var op = node.Operator switch
        {
            ComparisonOperator.GreaterThan => ">",
            ComparisonOperator.LessThan => "<",
            ComparisonOperator.GreaterThanOrEqual => ">=",
            ComparisonOperator.LessThanOrEqual => "<=",
            ComparisonOperator.Equal => "==",
            ComparisonOperator.NotEqual => "!=",
            _ => "=="
        };
        return $"{left} {op} {right}";
    }

    private static string TranslateCrossPineScript(CrossNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var left = TranslateValuePineScript(node.Left, indicators, warnings);
        var right = TranslateValuePineScript(node.Right, indicators, warnings);

        return node.Direction == CrossDirection.Above
            ? $"ta.crossover({left}, {right})"
            : $"ta.crossunder({left}, {right})";
    }

    private static string TranslateValuePineScript(ValueNode node, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        switch (node)
        {
            case LiteralNode literal:
                return literal.Value.ToString(CultureInfo.InvariantCulture);

            case PriceRefNode price:
                return price.Field switch
                {
                    PriceField.Open => "open",
                    PriceField.High => "high",
                    PriceField.Low => "low",
                    PriceField.Close => "close",
                    PriceField.Volume => "volume",
                    _ => "close"
                };

            case IndicatorRefNode indRef:
                return GetPineScriptIndicatorVariable(indRef, indicators, warnings);

            default:
                return "0";
        }
    }

    private static string GetPineScriptIndicatorVariable(IndicatorRefNode indRef, IReadOnlyList<IndicatorConfig> indicators, List<string> warnings)
    {
        var ind = indicators.FirstOrDefault(i => string.Equals(i.Id, indRef.IndicatorId, StringComparison.OrdinalIgnoreCase));

        if (ind is null)
        {
            warnings.Add($"Unknown indicator reference '{indRef.IndicatorId}' in condition.");
            return $"0 // unknown: {indRef.IndicatorId}";
        }

        var type = ind.Type.ToLowerInvariant();

        // Handle sub-properties
        if (indRef.SubProperty is not null)
        {
            var sub = indRef.SubProperty;
            return type switch
            {
                "macd" => $"{ind.Id}_{sub}",
                "bollinger" => $"{ind.Id}_{sub}",
                "stochastic" => $"{ind.Id}_{sub}",
                "donchian" => $"{ind.Id}_{sub}",
                _ => ind.Id
            };
        }

        // Single-value indicators use their ID directly
        return type switch
        {
            "sma" or "ema" or "rsi" or "atr" => ind.Id,
            "macd" => $"{ind.Id}_Macd",
            "bollinger" => $"{ind.Id}_Middle",
            "stochastic" => $"{ind.Id}_K",
            "donchian" => $"{ind.Id}_Upper",
            _ => ind.Id
        };
    }

