    private static List<string> GetMQL5HandleRelease(IndicatorConfig ind)
    {
        var lines = new List<string>();
        var type = ind.Type.ToLowerInvariant();

        if (type is "sma" or "ema" or "rsi" or "atr" or "macd" or "bollinger" or "stochastic")
        {
            lines.Add($"IndicatorRelease(handle_{ind.Id});");
        }

        return lines;
    }

    private static List<string> GetMQL5BufferCopy(IndicatorConfig ind, List<string> warnings)
    {
        var lines = new List<string>();
        var type = ind.Type.ToLowerInvariant();
        var period = GetIntParam(ind.Parameters, "period", 14);

        switch (type)
        {
            case "sma":
            case "ema":
            case "rsi":
            case "atr":
                lines.Add($"double {ind.Id}_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 0, 0, 2, {ind.Id}_buf);");
                break;
            case "macd":
                lines.Add($"double {ind.Id}_Macd_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 0, 0, 2, {ind.Id}_Macd_buf);");
                lines.Add($"double {ind.Id}_Signal_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 1, 0, 2, {ind.Id}_Signal_buf);");
                break;
            case "bollinger":
                lines.Add($"double {ind.Id}_Middle_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 0, 0, 2, {ind.Id}_Middle_buf);");
                lines.Add($"double {ind.Id}_Upper_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 1, 0, 2, {ind.Id}_Upper_buf);");
                lines.Add($"double {ind.Id}_Lower_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 2, 0, 2, {ind.Id}_Lower_buf);");
                break;
            case "stochastic":
                lines.Add($"double {ind.Id}_K_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 0, 0, 2, {ind.Id}_K_buf);");
                lines.Add($"double {ind.Id}_D_buf[2];");
                lines.Add($"CopyBuffer(handle_{ind.Id}, 1, 0, 2, {ind.Id}_D_buf);");
                break;
            case "donchian":
            {
                lines.Add($"double {ind.Id}_Upper_0 = 0, {ind.Id}_Lower_0 = DBL_MAX;");
                lines.Add($"double {ind.Id}_Upper_1 = 0, {ind.Id}_Lower_1 = DBL_MAX;");
                lines.Add($"for (int i = 1; i <= {period}; i++) {{ double h = iHigh(Symbol(), PERIOD_CURRENT, i); double l = iLow(Symbol(), PERIOD_CURRENT, i); if (h > {ind.Id}_Upper_0) {ind.Id}_Upper_0 = h; if (l < {ind.Id}_Lower_0) {ind.Id}_Lower_0 = l; }}");
                lines.Add($"for (int i = 2; i <= {period} + 1; i++) {{ double h = iHigh(Symbol(), PERIOD_CURRENT, i); double l = iLow(Symbol(), PERIOD_CURRENT, i); if (h > {ind.Id}_Upper_1) {ind.Id}_Upper_1 = h; if (l < {ind.Id}_Lower_1) {ind.Id}_Lower_1 = l; }}");
                break;
            }
            default:
                lines.Add($"// NOTE: Unsupported indicator type '{ind.Type}'");
                break;
        }

        return lines;
    }

