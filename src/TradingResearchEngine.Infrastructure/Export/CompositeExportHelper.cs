    private static int GetIntParam(IReadOnlyDictionary<string, object>? parameters, string key, int defaultValue)
    {
        if (parameters is null || !parameters.TryGetValue(key, out var value))
            return defaultValue;

        return value switch
        {
            int i => i,
            long l => (int)l,
            double d => (int)d,
            decimal dec => (int)dec,
            string s when int.TryParse(s, out var parsed) => parsed,
            System.Text.Json.JsonElement je when je.TryGetInt32(out var ji) => ji,
            _ => defaultValue
        };
    }

    private static decimal GetDecimalParam(IReadOnlyDictionary<string, object>? parameters, string key, decimal defaultValue)
    {
        if (parameters is null || !parameters.TryGetValue(key, out var value))
            return defaultValue;

        return value switch
        {
            decimal d => d,
            double dbl => (decimal)dbl,
            float f => (decimal)f,
            int i => i,
            long l => l,
            string s when decimal.TryParse(s, NumberStyles.Any, CultureInfo.InvariantCulture, out var parsed) => parsed,
            System.Text.Json.JsonElement je when je.TryGetDecimal(out var jd) => jd,
            _ => defaultValue
        };
    }

    private static string Fmt(decimal value) => value.ToString(CultureInfo.InvariantCulture);

    /// <summary>
    /// Attempts to extract a <see cref="CompositeStrategyConfig"/> from a StrategyVersion's Parameters dictionary.
    /// Returns null if the parameters do not contain a valid composite config.
    /// </summary>
    public static CompositeStrategyConfig? ExtractCompositeConfig(Dictionary<string, object> parameters)
    {
        if (parameters.TryGetValue("compositeConfig", out var configObj))
        {
            if (configObj is System.Text.Json.JsonElement je)
            {
                try
                {
                    return System.Text.Json.JsonSerializer.Deserialize<CompositeStrategyConfig>(
                        je.GetRawText(),
                        new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
                }
                catch
                {
                    return null;
                }
            }

            if (configObj is CompositeStrategyConfig config)
                return config;
        }

        // Try to reconstruct from individual parameters
        if (parameters.TryGetValue("name", out var nameObj)
            && parameters.TryGetValue("indicators", out var indicatorsObj)
            && parameters.TryGetValue("entryCondition", out var entryObj)
            && parameters.TryGetValue("exitCondition", out var exitObj))
        {
            try
            {
                var json = System.Text.Json.JsonSerializer.Serialize(parameters);
                return System.Text.Json.JsonSerializer.Deserialize<CompositeStrategyConfig>(
                    json,
                    new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            }
            catch
            {
                return null;
            }
        }

        return null;
    }

