    private static string GenerateDonchianBreakout(Dictionary<string, object> parameters)
    {
        var period = GetIntParam(parameters, "period", 20);

        return $@"//+------------------------------------------------------------------+
//| Donchian Breakout EA (MQL5)                                       |
//| Generated by TradingResearchEngine                                |
//+------------------------------------------------------------------+
#property strict
#include <Trade\Trade.mqh>

// NOTE: Donchian channel computed manually via iHighest/iLowest
input int Period = {period};
input double LotSize = 0.1;

CTrade trade;

int OnInit()
{{
    return INIT_SUCCEEDED;
}}

void OnDeinit(const int reason)
{{
    // Cleanup
}}

void OnTick()
{{
    double upperChannel = 0, lowerChannel = DBL_MAX;
    for (int i = 1; i <= Period; i++)
    {{
        double high = iHigh(Symbol(), PERIOD_CURRENT, i);
        double low = iLow(Symbol(), PERIOD_CURRENT, i);
        if (high > upperChannel) upperChannel = high;
        if (low < lowerChannel) lowerChannel = low;
    }}

    double price = SymbolInfoDouble(Symbol(), SYMBOL_LAST);

    // Enter long on upper channel breakout
    if (price > upperChannel)
    {{
        if (PositionsTotal() == 0)
            trade.Buy(LotSize, Symbol(), 0, 0, 0, ""Donchian Buy"");
    }}
    // Exit on lower channel break
    else if (price < lowerChannel)
    {{
        for (int i = PositionsTotal() - 1; i >= 0; i--)
        {{
            if (PositionGetSymbol(i) == Symbol())
                trade.PositionClose(PositionGetTicket(i));
        }}
    }}
}}

void OnTrade()
{{
    // Trade event handler for position management
}}
";
    }

    private static string GenerateMacroRegime(Dictionary<string, object> parameters)
    {
        var shortPeriod = GetIntParam(parameters, "shortPeriod", 50);
        var longPeriod = GetIntParam(parameters, "longPeriod", 200);

        return $@"//+------------------------------------------------------------------+
//| Macro Regime EA (MQL5)                                            |
//| Generated by TradingResearchEngine                                |
//+------------------------------------------------------------------+
#property strict
#include <Trade\Trade.mqh>

// NOTE: Macro regime detection is simplified; backtest uses additional regime indicators
input int ShortPeriod = {shortPeriod};
input int LongPeriod = {longPeriod};
input double LotSize = 0.1;

CTrade trade;
int handleShort;
int handleLong;

int OnInit()
{{
    handleShort = iMA(Symbol(), PERIOD_CURRENT, ShortPeriod, 0, MODE_SMA, PRICE_CLOSE);
    handleLong = iMA(Symbol(), PERIOD_CURRENT, LongPeriod, 0, MODE_SMA, PRICE_CLOSE);
    return INIT_SUCCEEDED;
}}

void OnDeinit(const int reason)
{{
    IndicatorRelease(handleShort);
    IndicatorRelease(handleLong);
}}

void OnTick()
{{
    double shortMA[1], longMA[1];
    CopyBuffer(handleShort, 0, 0, 1, shortMA);
    CopyBuffer(handleLong, 0, 0, 1, longMA);

    // Bullish regime: short MA above long MA
    if (shortMA[0] > longMA[0])
    {{
        if (PositionsTotal() == 0)
            trade.Buy(LotSize, Symbol(), 0, 0, 0, ""Regime Buy"");
    }}
    // Bearish regime: exit
    else if (shortMA[0] < longMA[0])
    {{
        for (int i = PositionsTotal() - 1; i >= 0; i--)
        {{
            if (PositionGetSymbol(i) == Symbol())
                trade.PositionClose(PositionGetTicket(i));
        }}
    }}
}}

void OnTrade()
{{
    // Trade event handler for position management
}}
";
    }

    private static int GetIntParam(Dictionary<string, object> parameters, string key, int defaultValue)
    {
        if (parameters.TryGetValue(key, out var value))
        {
            return value switch
            {
                int i => i,
                long l => (int)l,
                double d => (int)d,
                decimal dec => (int)dec,
                string s when int.TryParse(s, out var parsed) => parsed,
                System.Text.Json.JsonElement je when je.TryGetInt32(out var ji) => ji,
                _ => defaultValue
            };
        }
        return defaultValue;
    }

    private static decimal GetDecimalParam(Dictionary<string, object> parameters, string key, decimal defaultValue)
    {
        if (parameters.TryGetValue(key, out var value))
        {
            return value switch
            {
                decimal d => d,
                double dbl => (decimal)dbl,
                float f => (decimal)f,
                int i => i,
                long l => l,
                string s when decimal.TryParse(s, NumberStyles.Any, CultureInfo.InvariantCulture, out var parsed) => parsed,
                System.Text.Json.JsonElement je when je.TryGetDecimal(out var jd) => jd,
                _ => defaultValue
            };
        }
        return defaultValue;
    }

    private static string Fmt(decimal value) => value.ToString(CultureInfo.InvariantCulture);

    private static string SanitizeName(string strategyType) =>
        strategyType.Replace("-", "_");
}
